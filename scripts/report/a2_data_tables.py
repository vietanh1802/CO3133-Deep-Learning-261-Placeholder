"""Write the A2 Part 1 tables and number macros from the SUIM EDA summary.

The report never quotes a dataset number by hand. This script reads
``results/a2/eda/suim/summary.json`` and the two training configs, and regenerates
three files under ``reports/a2/Tables/``: the per-class table, the split table, and
a macro file that the prose in ``Sections/3-Problem-and-Data.tex`` uses for every
count.
"""

import json
from collections import Counter
from pathlib import Path

from src.config.segmentation import load_segmentation_config
from src.data.suim import MASK_BIT_THRESHOLD
from src.data.transform import IMAGENET_MEAN, IMAGENET_STD
from src.eda.suim import DHASH_SIDE

SUMMARY_PATH = Path("results/a2/eda/suim/summary.json")
TABLE_DIR = Path("reports/a2/Tables")
CONFIGS = {
    "Unet": Path("configs/segmentation/suim/baseline.yaml"),
    "Deeplab": Path("configs/segmentation/suim/pretrained.yaml"),
}
HEADER = (
    f"% Generated by scripts/report/a2_data_tables.py from {SUMMARY_PATH.as_posix()}."
    " Do not edit.\n"
)

CLASS_TITLES = {
    "BW": "Background (waterbody)",
    "HD": "Human divers",
    "PF": "Aquatic plants and sea-grass",
    "WR": "Wrecks and ruins",
    "RO": "Robots and instruments",
    "RI": "Reefs and invertebrates",
    "FV": "Fish and vertebrates",
    "SR": "Sea-floor and rocks",
}
BACKGROUND = "BW"


def count(value: int) -> str:
    """Format an integer with a LaTeX-safe thousands separator."""
    return f"{value:,}".replace(",", "{,}")


def percent(fraction: float, digits: int = 1) -> str:
    """Format a 0 to 1 fraction as a percentage without the sign."""
    return f"{100 * fraction:.{digits}f}"


def gibibytes(size: int) -> str:
    """Format a byte count in GiB with one decimal."""
    return f"{size / 2**30:.1f}"


def triple(values: tuple[float, float, float]) -> str:
    """Format per-channel constants as a parenthesised list."""
    return "(" + ", ".join(f"{v:g}" for v in values) + ")"


def by_name(classes: list[dict]) -> dict[str, dict]:
    return {entry["name"]: entry for entry in classes}


def number_macros(summary: dict) -> dict[str, str]:
    """Collect every dataset number the Part 1 prose quotes."""
    train_val, test = summary["splits"]["train_val"], summary["splits"]["TEST"]
    duplicates, split = summary["duplicates"], summary["split"]
    halves = split["halves"]
    dropped = len(duplicates["dropped_from_train_val"])
    within = [g for g in duplicates["groups"] if g not in duplicates["groups_crossing_splits"]]
    resolutions = Counter(train_val["resolutions"]) + Counter(test["resolutions"])
    dominant, dominant_count = resolutions.most_common(1)[0]
    usable_total = summary["usable_pairs_total"]
    split_total = halves["train"]["images"] + halves["val"]["images"]
    pool, held_out = by_name(train_val["classes"]), by_name(test["classes"])
    image_bytes = train_val["image_bytes"] + test["image_bytes"]
    mask_bytes = train_val["mask_bytes"] + test["mask_bytes"]

    macros = {
        "suimTrainValOnDisk": count(train_val["pairs_on_disk"]),
        "suimTestOnDisk": count(test["pairs_on_disk"]),
        "suimOnDiskTotal": count(train_val["pairs_on_disk"] + test["pairs_on_disk"]),
        "suimUnpaired": count(
            sum(
                len(s["images_without_mask"]) + len(s["masks_without_image"])
                for s in (train_val, test)
            )
        ),
        "suimDecodeErrors": count(train_val["decode_errors"] + test["decode_errors"]),
        "suimSizeMismatches": count(train_val["size_mismatches"]),
        "suimOffCodeMasks": count(train_val["off_code_masks"]),
        "suimTestOffCodeMasks": count(test["off_code_masks"]),
        "suimOffCodeShareMin": percent(train_val["off_code_share_range"][0]),
        "suimOffCodeShareMax": percent(train_val["off_code_share_range"][1], 0),
        "suimQualityPassed": count(train_val["usable_pairs"] + dropped),
        "suimTestDuplicatesDropped": count(dropped),
        "suimTrainValUsable": count(train_val["usable_pairs"]),
        "suimTestUsable": count(test["usable_pairs"]),
        "suimUsableTotal": count(usable_total),
        "suimStorage": gibibytes(image_bytes + mask_bytes),
        "suimImageStorage": gibibytes(image_bytes),
        "suimMaskStorage": gibibytes(mask_bytes),
        "suimForegroundClasses": count(len(CLASS_TITLES) - 1),
        "suimResolutionCount": count(len(resolutions)),
        "suimDominantResolution": dominant.replace("x", r"$\times$"),
        "suimDominantResolutionShare": percent(dominant_count / usable_total, 0),
        "suimHashBits": count(DHASH_SIDE * DHASH_SIDE),
        "suimHashDistance": count(duplicates["hash_distance"]),
        "suimPixelTolerance": f"{duplicates['pixel_tolerance']:g}",
        "suimHashCandidates": count(duplicates["candidates_from_hash"]),
        "suimConfirmedPairs": count(duplicates["confirmed_by_pixels"]),
        "suimDuplicateGroups": count(len(duplicates["groups"])),
        "suimCrossSplitGroups": count(len(duplicates["groups_crossing_splits"])),
        "suimWithinGroups": count(len(within)),
        "suimWithinGroupImages": count(sum(len(g) for g in within)),
        "suimSplitGroups": count(split["group_count"]),
        "suimSplitSeed": count(split["seed"]),
        "suimValFolds": count(split["val_fold_of"]),
        "suimTrainImages": count(halves["train"]["images"]),
        "suimValImages": count(halves["val"]["images"]),
        "suimTrainPercent": percent(halves["train"]["images"] / split_total),
        "suimValPercent": percent(halves["val"]["images"] / split_total),
        "suimMaxShareGap": percent(
            max(
                abs(
                    halves["train"]["classes"][n]["pixel_share"]
                    - halves["val"]["classes"][n]["pixel_share"]
                )
                for n in CLASS_TITLES
            )
        ),
    }
    for name in CLASS_TITLES:
        macros[f"suimShareTrainVal{name}"] = percent(pool[name]["pixel_share"], 2)
        macros[f"suimShareTest{name}"] = percent(held_out[name]["pixel_share"], 2)
        macros[f"suimMedianArea{name}"] = percent(pool[name]["median_area_when_present"])
        macros[f"suimImagesTrainVal{name}"] = count(pool[name]["images"])
        for half in ("train", "val"):
            entry = halves[half]["classes"][name]
            prefix = half.capitalize()
            macros[f"suimImages{prefix}{name}"] = count(entry["images"])
            macros[f"suimShare{prefix}{name}"] = percent(entry["pixel_share"])
    same_size, taller = summary["audit_examples"]["off_code_masks"]
    lowest, highest = summary["audit_examples"]["cross_split_pairs"]
    macros["suimOffCodeShareSameSize"] = percent(same_size["off_code_share"], 0)
    macros["suimOffCodeShareTaller"] = percent(taller["off_code_share"], 0)
    macros["suimTallerExtraRows"] = count(taller["mask_size"][1] - taller["image_size"][1])
    macros["suimDuplicateScoreLowest"] = f"{lowest['pixel_difference']:.1f}"
    macros["suimDuplicateScoreHighest"] = f"{highest['pixel_difference']:.1f}"
    foreground = [n for n in CLASS_TITLES if n != BACKGROUND]
    largest = max(foreground, key=lambda n: pool[n]["pixel_share"])
    smallest = min(foreground, key=lambda n: pool[n]["pixel_share"])
    macros["suimImbalanceRatio"] = count(
        round(pool[largest]["pixel_share"] / pool[smallest]["pixel_share"])
    )
    macros.update(preprocessing_macros(summary["example_batch"]))
    return macros


def preprocessing_macros(batch: dict) -> dict[str, str]:
    """Input size, normalization, batch sizes and the example batch quoted in Part 1."""
    configs = {name: load_segmentation_config(path) for name, path in CONFIGS.items()}
    sizes = {(c.image_height, c.image_width) for c in configs.values()}
    if len(sizes) != 1:
        raise ValueError(f"the models use different input sizes: {sorted(sizes)}")
    ((height, width),) = sizes
    macros = {
        "suimInputHeight": count(height),
        "suimInputWidth": count(width),
        "suimMaskThreshold": count(MASK_BIT_THRESHOLD),
        "suimNormMean": triple(IMAGENET_MEAN),
        "suimNormStd": triple(IMAGENET_STD),
        "suimExampleBatchSize": count(batch["image_shape"][0]),
        "suimExampleFlipped": count(sum(batch["flipped"])),
        "suimExampleClasses": count(len(batch["mask_classes"])),
        "suimExampleValueMin": f"{batch['image_range'][0]:.2f}",
        "suimExampleValueMax": f"{batch['image_range'][1]:.2f}",
    }
    for name, config in configs.items():
        macros[f"suim{name}Batch"] = count(config.batch_size)
        macros[f"suim{name}Accumulation"] = count(config.accumulation_steps)
        macros[f"suim{name}EffectiveBatch"] = count(config.batch_size * config.accumulation_steps)
    return macros


def macro_file(macros: dict[str, str]) -> str:
    lines = [rf"\newcommand{{\{name}}}{{{value}}}" for name, value in macros.items()]
    return HEADER + "\n".join(lines) + "\n"


def class_table(summary: dict) -> str:
    """Per-class image count, pixel share and region size, with the test share beside it."""
    pool = by_name(summary["splits"]["train_val"]["classes"])
    held_out = by_name(summary["splits"]["TEST"]["classes"])
    rows = [
        f"{name} & {title} & {count(pool[name]['images'])} & "
        f"{percent(pool[name]['pixel_share'], 2)} & "
        f"{percent(pool[name]['median_area_when_present'])} & "
        f"{percent(held_out[name]['pixel_share'], 2)}\\\\"
        for name, title in CLASS_TITLES.items()
    ]
    return (
        HEADER
        + "\n".join(
            [
                r"\begin{table}[htbp]",
                r"\centering\small",
                r"\caption{Per-class statistics. Images, pixel share and median area are",
                r"computed on the usable train and validation pool; median area is the class",
                r"fraction of an image, over images that contain the class. The last column is",
                r"the pixel share on the official test set.}",
                r"\label{tab:eda-classes}",
                r"\begin{tabular}{llrrrr}",
                r"\toprule",
                r"Code & Class & Images & Pixels (\%) & Median area (\%) & Test pixels (\%)\\",
                r"\midrule",
                *rows,
                r"\bottomrule",
                r"\end{tabular}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


def split_table(summary: dict) -> str:
    """Image counts per split with their share of the usable pairs."""
    halves = summary["split"]["halves"]
    total = summary["usable_pairs_total"]
    rows = [
        ("Train", halves["train"]["images"], "Official train pool", "Optimization"),
        ("Validation", halves["val"]["images"], "Official train pool", "Checkpoint selection"),
        (
            "Test",
            summary["splits"]["TEST"]["usable_pairs"],
            "Official test set",
            "Final evaluation only",
        ),
    ]
    body = [
        f"{split} & {count(images)} & {percent(images / total)} & {source} & {use}\\\\"
        for split, images, source, use in rows
    ]
    return (
        HEADER
        + "\n".join(
            [
                r"\begin{table}[htbp]",
                r"\centering\small",
                r"\caption{SUIM splits. The official test set is held out; train and validation",
                rf"come from the official training pool with seed {summary['split']['seed']}.}}",
                r"\label{tab:data-splits}",
                r"\begin{tabular}{lrrll}",
                r"\toprule",
                r"Split & Images & Share (\%) & Source & Use\\",
                r"\midrule",
                *body,
                r"\midrule",
                f"Total & {count(total)} & {percent(1.0)} & & \\\\",
                r"\bottomrule",
                r"\end{tabular}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


def main() -> None:
    summary = json.loads(SUMMARY_PATH.read_text(encoding="utf-8"))
    outputs = {
        "data_numbers.tex": macro_file(number_macros(summary)),
        "eda_classes.tex": class_table(summary),
        "data_splits.tex": split_table(summary),
    }
    for name, text in outputs.items():
        (TABLE_DIR / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TABLE_DIR / name}")


if __name__ == "__main__":
    main()
