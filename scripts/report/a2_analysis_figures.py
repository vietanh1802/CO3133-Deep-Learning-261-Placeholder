"""Build A2 qualitative panels and analysis tables from saved validation evidence.

Run from the repository root: uv run python -m scripts.report.a2_analysis_figures
"""

import csv
import json
import shutil
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import torch
from matplotlib.patches import Patch

from src.data.suim import CLASS_NAMES, IMAGENET_MEAN, IMAGENET_STD
from src.models import build_model
from src.plots.common import save_figure
from src.plots.format import apply

OUTPUT = Path("reports/a2/Images/analysis")
TABLES = Path("reports/a2/Tables")


def main() -> None:
    """Pair predictions by sample ID and export reproducible report evidence."""
    OUTPUT.mkdir(parents=True, exist_ok=True)
    runs = ["suim_ablation_reference_seed42"]
    reference = torch.load(
        Path("results/a2") / runs[0] / "val_evidence.pt",
        weights_only=True,
        map_location="cpu",
    )
    ids = reference["sample_ids"]
    assert reference["split"] == "validation" and len(ids) == len(set(ids)) == 287
    targets = reference["targets"].numpy()
    predictions = reference["predictions"].numpy()
    assert targets.shape == predictions.shape == (287, 240, 320)
    for labels in (targets, predictions):
        assert labels.min() >= 0 and labels.max() < 8
    checkpoint = torch.load(
        "checkpoints/suim_unet_seed42/best.pt", weights_only=True, map_location="cpu"
    )
    config = checkpoint["metadata"]["config"]
    assert config["model"] == "unet"
    model = build_model(config["model"], config["model_config"])
    model.load_state_dict(checkpoint["model"], strict=True)
    model.eval()
    torch.set_num_threads(4)
    mean = torch.tensor(IMAGENET_MEAN).view(3, 1, 1)
    std = torch.tensor(IMAGENET_STD).view(3, 1, 1)
    analysis = json.loads(Path("web/images/a2/errors/analysis.json").read_text())
    assert analysis["run"] == runs[0]
    palette = np.array([[(i >> bit) & 1 for bit in (2, 1, 0)] for i in range(8)], dtype=float)
    apply()
    figure, axes = plt.subplots(3, 4, figsize=(6.3, 4.5), layout="constrained")
    for row, label in enumerate(("best", "robot", "worst")):
        name = analysis["examples"][label]["sample_id"]
        index = ids.index(name)
        image = reference["images"][index]
        assert image.shape == (3, 240, 320) and torch.isfinite(image).all()
        assert 0 <= image.min() <= image.max() <= 1
        with torch.inference_mode():
            logits = model(((image - mean) / std).unsqueeze(0))
        assert logits.shape == (1, 8, 240, 320) and torch.isfinite(logits).all()
        unet_prediction = logits.argmax(1)[0].numpy()
        panels = (
            reference["images"][index].numpy().transpose(1, 2, 0),
            palette[targets[index]],
            palette[unet_prediction],
            palette[predictions[index]],
        )
        for col, (axis, panel) in enumerate(zip(axes[row], panels, strict=True)):
            axis.imshow(panel)
            axis.axis("off")
            if row == 0:
                axis.set_title(("Input", "Ground truth", "U-Net", "DeepLabV3")[col])
        axes[row, 0].text(
            0.5, -0.08, name, transform=axes[row, 0].transAxes, ha="center", fontsize=7
        )
    figure.legend(
        handles=[
            Patch(facecolor=palette[i], edgecolor="0.5", label=name)
            for i, name in enumerate(CLASS_NAMES)
        ],
        loc="outside lower center",
        ncol=8,
        columnspacing=0.8,
        handlelength=1,
    )
    save_figure(figure, OUTPUT / "qualitative_examples.png")
    plt.close(figure)
    counts = np.bincount(
        8 * targets.astype(np.int64).ravel() + predictions.ravel(), minlength=64
    ).reshape(8, 8)
    assert counts.sum() == 287 * 240 * 320
    macros = {
        "plantsAsReef": f"{100 * counts[2, 5] / counts[2].sum():.2f}",
        "robotsAsDivers": f"{100 * counts[4, 1] / counts[4].sum():.2f}",
        "referenceMedianImageIoU": f"{100 * analysis['median_per_image_miou']:.2f}",
    }
    summary = json.loads(
        Path("results/a2/suim_ablation_reference_seed42/training_summary.json").read_text()
    )
    for region in ("boundary", "interior"):
        macros[f"reference{region.title()}IoU"] = (
            f"{100 * summary['validation'][region]['mean_iou']:.2f}"
        )
    (TABLES / "analysis_numbers.tex").write_text(
        "% Generated by scripts/report/a2_analysis_figures.py.\n"
        + "\n".join(rf"\newcommand{{\{key}}}{{{value}}}" for key, value in macros.items())
        + "\n"
    )
    labels = (
        "Reference",
        "Frozen backbone",
        "No augmentation",
        "ResNet101",
        "CE + Dice",
        "Half resolution",
    )
    with Path("results/a2/ablation/comparisons.csv").open() as stream:
        rows = list(csv.DictReader(stream))
    assert len(rows) == len(labels) and {row["seed"] for row in rows} == {"42"}
    body = [
        f"{label} & {100 * float(row['miou']):.2f} & {100 * float(row['mean_dice']):.2f} & "
        f"{float(row['delta_miou_pp']):+.2f} & {100 * float(row['boundary_miou']):.2f}" + r"\\"
        for label, row in zip(labels, rows, strict=True)
    ]
    (TABLES / "ablation.tex").write_text(
        "\n".join(
            [
                "% Generated by scripts/report/a2_analysis_figures.py from comparisons.csv.",
                r"\begin{table}[htbp]",
                r"\centering\small",
                r"\caption{Controlled comparisons on the same validation split, with seed 42. "
                r"Scores are percentages; $\Delta$ mIoU is the change from the reference "
                r"in percentage points.}",
                r"\label{tab:ablation}",
                r"\begin{tabular}{lrrrr}",
                r"\toprule",
                r"Configuration & mIoU & Mean Dice & $\Delta$ mIoU & Boundary mIoU\\",
                r"\midrule",
                *body,
                r"\bottomrule",
                r"\end{tabular}",
                r"\end{table}",
                "",
            ]
        )
    )
    for name in ("confusion_matrix", "regional_iou", "per_image_iou", "rare_class_failures"):
        for suffix in ("png", "pdf"):
            shutil.copyfile(
                Path(f"web/images/a2/errors/{name}.{suffix}"), OUTPUT / f"{name}.{suffix}"
            )
    print(json.dumps(macros, indent=2))


if __name__ == "__main__":
    main()
