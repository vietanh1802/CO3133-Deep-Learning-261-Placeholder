"""Write the A2 Part 3 compute-cost table and number macros from the run records.

The results section never quotes a number by hand. This script reads the U-Net
``training_summary.json`` and the DeepLabV3 rows of the ablation results, counts
the floating-point operations of each model for one input image, and regenerates
two files under ``reports/a2/Tables/``: the compute-cost table and a macro file
used by ``Sections/5-Implementation-Results.tex``.
"""

import csv
import json
from pathlib import Path

import torch
from torch.utils.flop_counter import FlopCounterMode

from scripts.report.a2_data_tables import count
from scripts.report.a2_method_tables import device_name
from src.models.deeplabv3 import DeepLabV3
from src.models.unet import UNet

UNET_SUMMARY = Path("results/a2/suim_unet_seed42/training_summary.json")
COMPARISONS = Path("results/a2/ablation/comparisons.csv")
DEEPLAB_RUNS = {"Ce": "suim_ablation_reference_seed42", "Dice": "suim_ablation_ce_dice_seed42"}
TABLE_DIR = Path("reports/a2/Tables")
HEADER = (
    "% Generated by scripts/report/a2_results_tables.py from the U-Net training summary"
    " and the ablation results. Do not edit.\n"
)


def gigaflops(model: torch.nn.Module, height: int, width: int) -> float:
    """Forward FLOPs for one image, counting a multiply and an add as two operations."""
    model.eval()
    with torch.no_grad(), FlopCounterMode(display=False) as counter:
        model(torch.zeros(1, 3, height, width))
    return counter.get_total_flops() / 1e9


def gigabytes(megabytes: float) -> str:
    return f"{megabytes / 1024:.2f}"


def unet_macros(summary: dict) -> dict[str, str]:
    """Numbers that describe the U-Net learning curves and the selected checkpoint."""
    history = summary["history"]
    best = history[summary["best_epoch"] - 1]
    last, first = history[-1], history[0]
    warmup = history[summary["config"]["warmup_epochs"] - 1]
    lowest = min(history, key=lambda record: record["validation_loss"])
    iou = summary["validation"]["all"]["per_class_iou"]
    return {
        "unetBestEpoch": count(summary["best_epoch"]),
        "unetBestValMiou": f"{100 * best['validation_miou']:.1f}",
        "unetWarmupValMiou": f"{100 * warmup['validation_miou']:.1f}",
        "unetLastGap": f"{100 * (best['validation_miou'] - last['validation_miou']):.2f}",
        "unetFirstTrainLoss": f"{first['train_loss']:.2f}",
        "unetLastTrainLoss": f"{last['train_loss']:.2f}",
        "unetLowestValLossEpoch": count(lowest["epoch"]),
        "unetValBelowTrain": count(sum(r["validation_loss"] < r["train_loss"] for r in history)),
        "unetLossGap": f"{max(r['validation_loss'] - r['train_loss'] for r in history):.2f}",
        "unetZeroClasses": " and ".join(name for name, value in iou.items() if value == 0),
        "unetTrainMinutes": f"{summary['training_seconds'] / 60:.1f}",
        "unetEpochSeconds": f"{summary['training_seconds'] / len(history):.0f}",
        "unetLatency": f"{summary['validation_inference']['milliseconds_per_image']:.1f}",
        "unetInferenceBatch": count(summary["validation_inference"]["batch_size"]),
        "unetPeakMemory": gigabytes(summary["peak_training_memory_mb"]),
    }


def cost_macros(summary: dict, deeplab: dict[str, dict]) -> dict[str, str]:
    """Size, operations, time and memory of every reported model."""
    height, width = summary["config"]["image_height"], summary["config"]["image_width"]
    unet_flops = gigaflops(UNet(**summary["config"]["model_config"]), height, width)
    deeplab_flops = gigaflops(DeepLabV3(pretrained=False), height, width)
    overhead = deeplab["Dice"]["training_seconds"] / deeplab["Ce"]["training_seconds"] - 1
    macros = {
        "unetGflops": f"{unet_flops:.1f}",
        "deeplabGflops": f"{deeplab_flops:.1f}",
        "flopRatio": f"{deeplab_flops / unet_flops:.1f}",
        "deeplabMillions": f"{deeplab['Ce']['parameters'] / 1e6:.2f}",
        "diceTimeOverhead": f"{100 * overhead:.0f}",
    }
    for key, row in deeplab.items():
        macros[f"deeplab{key}TrainMinutes"] = f"{row['training_seconds'] / 60:.1f}"
        macros[f"deeplab{key}Latency"] = f"{row['inference_ms_per_image']:.1f}"
        macros[f"deeplab{key}PeakMemory"] = gigabytes(row["peak_training_memory_mb"])
    return macros


def cost_table(summary: dict, macros: dict[str, str]) -> str:
    """Compute cost per model. DeepLabV3 hardware is not recorded in the ablation results."""
    unet = (
        rf"U-Net & {summary['parameters'] / 1e6:.2f} & {macros['unetGflops']} & "
        rf"{macros['unetTrainMinutes']} & {macros['unetLatency']} & "
        rf"{macros['unetPeakMemory']} & {device_name(summary['device']).removesuffix(' GPU')}\\"
    )
    rows = [unet]
    for key, label in (("Ce", "DeepLabV3 (CE)"), ("Dice", "DeepLabV3 (CE + Dice)")):
        rows.append(
            rf"{label} & {macros['deeplabMillions']} & {macros['deeplabGflops']} & "
            rf"{macros[f'deeplab{key}TrainMinutes']} & {macros[f'deeplab{key}Latency']} & "
            rf"{macros[f'deeplab{key}PeakMemory']} & \pending\\"
        )
    return (
        HEADER
        + "\n".join(
            [
                r"\begin{table}[htbp]",
                r"\centering\small",
                r"\caption{Compute cost. GFLOPs are counted for one $\suimInputHeight\times"
                r"\suimInputWidth$ image and do not depend on hardware. Training time, latency",
                r"and peak training memory are measured on the hardware listed; latency excludes",
                rf"data loading and is measured on the validation set at batch size"
                rf" {macros['unetInferenceBatch']}.}}",
                r"\label{tab:compute-cost}",
                r"\footnotesize\setlength{\tabcolsep}{3pt}",
                r"\begin{tabular}{lrrrrrl}",
                r"\toprule",
                r"& & & Train time & Latency & Peak memory & Training\\",
                r"Model & Params (M) & GFLOPs & (min) & (ms/image) & (GB) & hardware\\",
                r"\midrule",
                *rows,
                r"\bottomrule",
                r"\end{tabular}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


def macro_file(macros: dict[str, str]) -> str:
    lines = [rf"\newcommand{{\{name}}}{{{value}}}" for name, value in macros.items()]
    return HEADER + "\n".join(lines) + "\n"


def main() -> None:
    summary = json.loads(UNET_SUMMARY.read_text(encoding="utf-8"))
    with COMPARISONS.open(encoding="utf-8", newline="") as handle:
        rows = {row["run"]: row for row in csv.DictReader(handle)}
    deeplab = {
        key: {name: float(value) for name, value in rows[run].items() if name != "run"}
        for key, run in DEEPLAB_RUNS.items()
    }
    macros = unet_macros(summary) | cost_macros(summary, deeplab)
    outputs = {
        "results_numbers.tex": macro_file(macros),
        "compute_cost.tex": cost_table(summary, macros),
    }
    for name, text in outputs.items():
        (TABLE_DIR / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TABLE_DIR / name}")


if __name__ == "__main__":
    main()
