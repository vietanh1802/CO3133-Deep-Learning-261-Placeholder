"""Write the A2 Part 2 model table and number macros from the run records.

The methodology never quotes a model number by hand. This script reads the U-Net
``training_summary.json``, the reference row of the ablation results (the
official DeepLabV3 cross-entropy run), the torchvision weight metadata, and the
model code itself, and regenerates two files under ``reports/a2/Tables/``: the
model summary table and a macro file used by ``Sections/4-Methodology.tex``.
"""

import csv
import json
from math import log10
from pathlib import Path

import torch
from torchvision.models.segmentation import DeepLabV3_ResNet50_Weights

from scripts.report.a2_data_tables import count
from src.models.deeplabv3 import DeepLabV3
from src.models.unet import UNet

UNET_SUMMARY = Path("results/a2/suim_unet_seed42/training_summary.json")
ABLATION_DIR = Path("results/a2/ablation")
DEEPLAB_RUN = "suim_ablation_reference_seed42"
WEIGHTS = DeepLabV3_ResNet50_Weights.COCO_WITH_VOC_LABELS_V1
TABLE_DIR = Path("reports/a2/Tables")
HEADER = (
    "% Generated by scripts/report/a2_method_tables.py from the U-Net training summary,"
    " the ablation results and the model code. Do not edit.\n"
)


def rate(value: float) -> str:
    """Format a learning rate, as a power of ten when it is one."""
    exponent = round(log10(value))
    return rf"$10^{{{exponent}}}$" if 10.0**exponent == value else f"{value:g}"


def listing(values: list[int]) -> str:
    """Join numbers as an English list: 12, 24 and 36."""
    words = [str(v) for v in values]
    return ", ".join(words[:-1]) + " and " + words[-1]


def deeplab_structure(height: int, width: int) -> dict[str, str]:
    """Read the ASPP layout and output stride from an untrained copy of the model."""
    model = DeepLabV3(pretrained=False).eval()
    aspp = model.network.classifier[0]
    rates = [branch[0].dilation[0] for branch in aspp.convs[1:-1]]
    with torch.no_grad():
        features = model.network.backbone(torch.zeros(1, 3, height, width))["out"]
    return {
        "deeplabAtrousRates": listing(rates),
        "deeplabAsppChannels": count(aspp.project[0].out_channels),
        "deeplabBackboneChannels": count(features.shape[1]),
        "deeplabOutputStride": count(height // features.shape[2]),
        "deeplabFeatureHeight": count(features.shape[2]),
        "deeplabFeatureWidth": count(features.shape[3]),
    }


def number_macros(unet: dict, deeplab: dict, deeplab_config: dict) -> dict[str, str]:
    """Collect every model number the Part 2 prose quotes."""
    config = unet["config"]
    base = config["model_config"]["base_width"]
    height, width = config["image_height"], config["image_width"]
    # The report states that every DeepLabV3 parameter is trained.
    if deeplab["parameters"] != deeplab["trainable_parameters"]:
        raise ValueError("the DeepLabV3 run froze some parameters")
    macros = {
        "unetParameters": count(unet["parameters"]),
        "unetDepth": count(UNet.depth),
        "unetWidthFirst": count(base),
        "unetWidthLast": count(base * 2**UNet.depth),
        "unetDownsample": count(2**UNet.depth),
        "unetBottleneckHeight": count(height // 2**UNet.depth),
        "unetBottleneckWidth": count(width // 2**UNet.depth),
        "unetWorkers": count(config["num_workers"]),
        "deeplabParameters": count(int(deeplab["parameters"])),
        "deeplabLibraryParameters": count(WEIGHTS.meta["num_params"]),
        "deeplabLibraryCategories": count(len(WEIGHTS.meta["categories"])),
        "deeplabLibraryMiou": f"{WEIGHTS.meta['_metrics']['COCO-val2017-VOC-labels']['miou']:g}",
        "deeplabHeadRate": rate(deeplab_config["learning_rate"]),
        "deeplabBackboneRate": rate(deeplab_config["backbone_learning_rate"]),
        "deeplabBatch": count(deeplab_config["batch_size"]),
        "parameterRatio": f"{int(deeplab['parameters']) / unet['parameters']:.1f}",
        "unetLearningRate": rate(config["learning_rate"]),
        "unetWeightDecay": rate(config["weight_decay"]),
        "unetEpochs": count(config["epochs"]),
        "unetWarmupEpochs": count(config["warmup_epochs"]),
        "unetSeed": count(config["seed"]),
        "unetDevice": device_name(unet["device"]),
        "unetTorchVersion": release(unet["software"]["torch"]),
        "unetCudaVersion": unet["software"]["cuda"],
    }
    macros.update(deeplab_structure(height, width))
    return macros


def device_name(name: str) -> str:
    """Shorten a CUDA device name for a table cell."""
    return name.removeprefix("NVIDIA ").removeprefix("GeForce ")


def release(version: str) -> str:
    """Drop the local build tag from a package version, e.g. 2.14.0+cu130."""
    return version.split("+")[0]


def training_table(unet: dict, macros: dict[str, str]) -> str:
    """Settings of the reported runs. The DeepLabV3 column is filled in by its owner."""
    config = unet["config"]
    batch, accumulation = config["batch_size"], config["accumulation_steps"]
    rows = [
        ("Input size", rf"${config['image_height']}\times{config['image_width']}$"),
        ("Initialization", "Random"),
        ("Optimizer", "AdamW"),
        ("Learning rate", macros["unetLearningRate"]),
        ("Scheduler", f"{config['warmup_epochs']}-epoch linear warm-up, cosine"),
        ("Batch size (effective)", f"{batch} ({batch * accumulation})"),
        ("Epochs / seed", f"{config['epochs']} / {config['seed']}"),
        ("Weight decay", macros["unetWeightDecay"]),
        ("Augmentation", "Horizontal flip"),
        ("Loss", "Cross-entropy"),
        ("Mixed precision", "Yes" if unet["mixed_precision"] else "No"),
        ("Checkpoint rule", "Best validation mIoU"),
        ("Hardware", macros["unetDevice"]),
        ("Software", f"PyTorch {macros['unetTorchVersion']}, CUDA {macros['unetCudaVersion']}"),
    ]
    body = [rf"{setting} & {value} & \pending\\" for setting, value in rows]
    return (
        HEADER
        + "\n".join(
            [
                r"\begin{table}[htbp]",
                r"\centering\small",
                r"\caption{Training settings of the reported runs.}",
                r"\label{tab:training-setup}",
                r"\begin{tabular}{lll}",
                r"\toprule",
                r"Setting & U-Net & DeepLabV3\\",
                r"\midrule",
                *body,
                r"\bottomrule",
                r"\end{tabular}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


def macro_file(macros: dict[str, str]) -> str:
    lines = [rf"\newcommand{{\{name}}}{{{value}}}" for name, value in macros.items()]
    return HEADER + "\n".join(lines) + "\n"


def model_table(macros: dict[str, str]) -> str:
    """Role, initialization, origin and size of the two compared models."""
    return (
        HEADER
        + "\n".join(
            [
                r"\begin{table}[htbp]",
                r"\centering\small",
                r"\caption{Compared models. Implementation states whether the group wrote the",
                r"model or used a library.}",
                r"\label{tab:model-summary}",
                r"\begin{tabular}{llllr}",
                r"\toprule",
                r"Model & Role & Initialization & Implementation & Parameters\\",
                r"\midrule",
                rf"U-Net & Baseline & Random & Group & {macros['unetParameters']}\\",
                r"DeepLabV3 (ResNet-50) & Pretrained & COCO, VOC labels & torchvision, new head"
                rf" & {macros['deeplabParameters']}\\",
                r"\bottomrule",
                r"\end{tabular}",
                r"\end{table}",
            ]
        )
        + "\n"
    )


def main() -> None:
    unet = json.loads(UNET_SUMMARY.read_text(encoding="utf-8"))
    with (ABLATION_DIR / "comparisons.csv").open(encoding="utf-8", newline="") as handle:
        deeplab = next(row for row in csv.DictReader(handle) if row["run"] == DEEPLAB_RUN)
    manifest = json.loads((ABLATION_DIR / "manifest.json").read_text(encoding="utf-8"))
    macros = number_macros(unet, deeplab, manifest[DEEPLAB_RUN])
    outputs = {
        "method_numbers.tex": macro_file(macros),
        "model_summary.tex": model_table(macros),
        "training_setup.tex": training_table(unet, macros),
    }
    for name, text in outputs.items():
        (TABLE_DIR / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TABLE_DIR / name}")


if __name__ == "__main__":
    main()
