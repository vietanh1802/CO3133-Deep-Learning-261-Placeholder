"""Write the images and numbers behind the A2 preprocessing figure.

The figure in ``Sections/3-Problem-and-Data.tex`` follows one SUIM pair through
loading, resizing, flipping and normalization, then shows the example batch of
the EDA summary. This script produces every picture in it with the project's own
data code and writes the size of the original photograph as a macro, so the
figure quotes no number by hand.

Run from the repository root: uv run python -m scripts.report.a2_preprocessing_figure
"""

import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from PIL import Image

from scripts.report.a2_data_tables import count
from src.data.suim import SuimSegmentation, decode_mask
from src.plots.format import apply

SUMMARY = Path("results/a2/eda/suim/summary.json")
DATA_DIR = Path("data/suim")
SPLIT_DIR = Path("results/a2/splits/suim")
OUTPUT = Path("reports/a2/Images/preprocessing")
MACROS = Path("reports/a2/Tables/preprocessing_numbers.tex")
HEADER = (
    "% Generated by scripts/report/a2_preprocessing_figure.py from the SUIM data"
    " and the EDA summary. Do not edit.\n"
)
# A 16:9 photograph from the example batch, so the figure shows the stretch to 4:3.
EXAMPLE = "d_r_700_"
# Width of the original-size thumbnails; the resized ones keep their 320 pixels.
RAW_WIDTH = 640
PALETTE = np.array([[(i >> bit) & 1 for bit in (2, 1, 0)] for i in range(8)], dtype=np.uint8) * 255


def save_photo(pixels: np.ndarray, name: str) -> None:
    Image.fromarray(pixels).save(OUTPUT / f"{name}.jpg", quality=92)


def save_mask(labels: np.ndarray, name: str) -> None:
    Image.fromarray(PALETTE[labels]).save(OUTPUT / f"{name}.png")


def to_photo(pixels, mean: np.ndarray, std: np.ndarray) -> np.ndarray:
    """Undo the normalization of one image tensor for display."""
    return ((pixels.numpy() * std + mean).transpose(1, 2, 0).clip(0, 1) * 255).astype(np.uint8)


def plot_histogram(pixels: np.ndarray, path: Path) -> None:
    """Per-channel histogram of normalized values, sized for a 2.5 cm wide slot."""
    apply()
    figure, axis = plt.subplots(figsize=(0.98, 0.74), dpi=600)
    bins = np.linspace(pixels.min(), pixels.max(), 60)
    for channel, colour in zip(pixels, ("#C0392B", "#27AE60", "#2E6FBF"), strict=True):
        axis.hist(channel.ravel(), bins=bins, histtype="stepfilled", alpha=0.35, color=colour)
        axis.hist(channel.ravel(), bins=bins, histtype="step", color=colour, linewidth=0.6)
    axis.axvline(0, color="0.3", linewidth=0.5, linestyle="--")
    axis.set_xticks([-2, 0, 2])
    axis.set_yticks([])
    axis.grid(False)
    axis.tick_params(labelsize=5, length=2, width=0.4, pad=1)
    for side in ("left", "top", "right"):
        axis.spines[side].set_visible(False)
    axis.spines["bottom"].set_linewidth(0.4)
    figure.subplots_adjust(left=0.03, right=0.97, bottom=0.2, top=0.98)
    figure.savefig(path, facecolor="white")
    plt.close(figure)


def main() -> None:
    batch = json.loads(SUMMARY.read_text(encoding="utf-8"))["example_batch"]
    if EXAMPLE not in batch["stems"]:
        raise ValueError(f"{EXAMPLE} is not in the example batch {batch['stems']}")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    dataset = SuimSegmentation(DATA_DIR, "train", split_dir=SPLIT_DIR)
    index = {image.stem: position for position, (image, _) in enumerate(dataset.pairs)}
    mean, std = dataset.mean.numpy(), dataset.std.numpy()

    # Original pair, scaled down for the page; the mask keeps exact class colours.
    image_path, mask_path = dataset.pairs[index[EXAMPLE]]
    with Image.open(image_path) as handle:
        raw = handle.convert("RGB")
    with Image.open(mask_path) as handle:
        labels = decode_mask(np.asarray(handle.convert("RGB"), dtype=np.uint8))
    width, height = raw.size
    size = (RAW_WIDTH, round(RAW_WIDTH * height / width))
    save_photo(np.asarray(raw.resize(size, Image.Resampling.BILINEAR)), "raw_image")
    small = Image.fromarray(labels).resize(size, Image.Resampling.NEAREST)
    save_mask(np.asarray(small), "raw_mask")

    # Resized, flipped and normalized versions, exactly as the loader returns them.
    pixels, target = dataset[index[EXAMPLE]]
    photo, mask = to_photo(pixels, mean, std), target.numpy()
    save_photo(photo, "resized_image")
    save_mask(mask, "resized_mask")
    save_photo(np.ascontiguousarray(photo[:, ::-1]), "flipped_image")
    save_mask(np.ascontiguousarray(mask[:, ::-1]), "flipped_mask")
    plot_histogram(pixels.numpy(), OUTPUT / "normalized_histogram.png")

    # The example batch, with each pair flipped as recorded in the summary.
    for position, (stem, flipped) in enumerate(zip(batch["stems"], batch["flipped"], strict=True)):
        pixels, target = dataset[index[stem]]
        photo, mask = to_photo(pixels, mean, std), target.numpy()
        if flipped:
            photo, mask = photo[:, ::-1], mask[:, ::-1]
        save_photo(np.ascontiguousarray(photo), f"batch_image_{position}")
        save_mask(np.ascontiguousarray(mask), f"batch_mask_{position}")

    macros = {"prepExampleWidth": count(width), "prepExampleHeight": count(height)}
    lines = [rf"\newcommand{{\{name}}}{{{value}}}" for name, value in macros.items()]
    MACROS.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT} and {MACROS}")


if __name__ == "__main__":
    main()
